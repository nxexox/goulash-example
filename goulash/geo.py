CITY_TO_REGION = {normalize(c): r for r, cities in REGIONS.items() for c in cities}
REGION_NAMES = list(REGIONS)


def _city_key(name: str) -> tuple[str, ...]:
    return tuple(stem(w) for w in words(name))


# stemmed multi-word key -> canonical city; longest keys are matched first.
_CITY_KEYS: dict[tuple[str, ...], str] = {}
for _cities in REGIONS.values():
    for _c in _cities:
        _CITY_KEYS[_city_key(_c)] = _c
for _alias, _c in ALIASES.items():
    _CITY_KEYS[(_alias,)] = _c
# Region names ("свердловская область", "республика адыгея") -> region. Kept apart from cities so an address
# in "Республика Адыгея, аул ..." yields the region without inventing a city.
_REGION_KEYS: dict[tuple[str, ...], str] = {}
for _r in REGIONS:
    _w = [w for w in words(_r) if w not in {"область", "край", "республика", "и", "ао"}]
    if len(_w) == 1 and not _w[0].startswith(("москв", "санкт")):
        _REGION_KEYS[(stem(_w[0]),)] = _r
_MAX_KEY = max(len(k) for k in _CITY_KEYS)


def region_of_city(city: str | None) -> str | None:
    return CITY_TO_REGION.get(normalize(city)) if city else None


def _scan(text: str, keys: dict[tuple[str, ...], str]) -> list[tuple[str, int, int]]:
    toks = [stem(w) for w in words(text)]
    found, i = [], 0
    while i < len(toks):
        for n in range(min(_MAX_KEY, len(toks) - i), 0, -1):
            hit = keys.get(tuple(toks[i : i + n]))
            if hit:
                found.append((hit, i, i + n))
                i += n
                break
        else:
            i += 1
    return found


def find_cities(text: str) -> list[tuple[str, int, int]]:
    """Return (canonical_city, start_word, end_word) for city mentions in text, longest match first."""
    return _scan(text, _CITY_KEYS)


def find_regions(text: str) -> list[tuple[str, int, int]]:
    """Return (region, start_word, end_word) for region names ("Краснодарский край") in text."""
    return _scan(text, _REGION_KEYS)


def city_from_address(address: str | None) -> str | None:
    """Best-effort city from a postal address like 'Россия, 193079, г. Санкт-Петербург, ...'."""
    if not address:
        return None
    m = re.search(r"\bг\.\s*([А-ЯЁ][\w\-]+(?:[\s\-][А-ЯЁ][\w\-]+)?)", address)
    if m and region_of_city(m.group(1)):
        return m.group(1)
    hits = find_cities(address)
    return hits[0][0] if hits else None


def region_from_address(address: str | None) -> str | None:
    if not address:
        return None
    hits = find_regions(address)
    return hits[0][0] if hits else region_of_city(city_from_address(address))
